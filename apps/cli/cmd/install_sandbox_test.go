// gVisor's runtime goes in a drop-in where k3s imports one, else in the
// template, in the syntax of the containerd k3s runs, and never over an
// operator's own template.
func TestContainerdRuntimeFile(t *testing.T) {
	const dir = "/c"
	v3Imports := "# File generated by k3s.\nversion = 3\nimports = [\"/c/config-v3.toml.d/*.toml\"]\n"
	none := func(string) ([]byte, bool) { return nil, false }
	theirs := func(string) ([]byte, bool) { return []byte("{{ template \"base\" . }}\n[their.stuff]\n"), true }
	ours := func(string) ([]byte, bool) { return []byte(sandboxConfMark + "\nold"), true }

	cases := []struct {
		what, generated string
		read            func(string) ([]byte, bool)
		path, table     string
		refused         bool
	}{
		{"v3 with a drop-in folder", v3Imports, theirs, "/c/config-v3.toml.d/meshploy-sandbox.toml", "'io.containerd.cri.v1.runtime'", false},
		{"v3 without one", "version = 3\n", none, "/c/config-v3.toml.tmpl", "'io.containerd.cri.v1.runtime'", false},
		{"v2", "version = 2\n", none, "/c/config.toml.tmpl", `"io.containerd.grpc.v1.cri"`, false},
		{"our own template again", "version = 3\n", ours, "/c/config-v3.toml.tmpl", "'io.containerd.cri.v1.runtime'", false},
		{"the operator's template", "version = 3\n", theirs, "", "", true},
	}
	for _, c := range cases {
		path, body, err := containerdRuntimeFile(c.generated, dir, c.read)
		if c.refused {
			if err == nil {
				t.Errorf("%s: wrote %s, want a refusal", c.what, path)
			}
			continue
		}
		if err != nil {
			t.Errorf("%s: %v", c.what, err)
			continue
		}
		if path != c.path || !strings.Contains(body, c.table) || !strings.Contains(body, `runtime_type = "io.containerd.runsc.v1"`) {
			t.Errorf("%s: got %s:\n%s", c.what, path, body)
		}
		if strings.HasSuffix(path, ".tmpl") != strings.Contains(body, `{{ template "base" . }}`) {
			t.Errorf("%s: a template must build on k3s's base, and only a template: %s", c.what, body)
		}
	}
}

func TestKubeletNodeName(t *testing.T) {
	cert := func(cn string) []byte {
		key, _ := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		tmpl := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: cn},
			NotBefore: time.Now(), NotAfter: time.Now().Add(time.Hour)}
		der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
		if err != nil {
			t.Fatal(err)
		}
		return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	}
	if name, err := kubeletNodeName(cert("system:node:worker-1")); err != nil || name != "worker-1" {
		t.Errorf("got %q, %v; want worker-1", name, err)
	}
	if _, err := kubeletNodeName(cert("system:admin")); err == nil {
		t.Error("a certificate for something other than a node was accepted")
	}
}

